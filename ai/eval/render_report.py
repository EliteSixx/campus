"""Render docs/EVALUATION.md from the generated evaluation JSON."""

import json
import sys
from pathlib import Path
from typing import Any

AI_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = AI_ROOT.parent
RESULTS_PATH = AI_ROOT / "eval" / "results.json"
REPORT_PATH = REPO_ROOT / "docs" / "EVALUATION.md"


def _decimal(value: Any, digits: int = 4) -> str:
    return "n/a" if value is None else f"{float(value):.{digits}f}"


def _percent(value: Any) -> str:
    return "n/a" if value is None else f"{float(value) * 100:.2f}%"


def _safe_cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(results: dict[str, Any]) -> str:
    matching = results["matching_vs_shortlisting"]
    ceiling = results["generator_shortlist_signal_ceiling"]
    eligibility = results["eligibility_gate_correctness"]
    readiness = results["readiness_vs_outcomes"]
    jds = results["jd_parser_accuracy"]
    skills = results["skill_matching"]
    risk = results["risk_model"]
    latency = results["latency"]

    lines = [
        "# CampusLink AI evaluation",
        "",
        "This report is generated by `ai/eval/render_report.py` from `ai/eval/results.json`. The fixed seed is 42. All placement and application outcomes used here are synthetic.",
        "",
        "## Method",
        "",
        f"- Pipeline matching mode: `{results['metadata']['matching_mode_for_pipeline_metrics']}`. Seeded random ranking uses one deterministic random score per application; the CGPA baseline ranks by CGPA only.",
        f"- Matching labels come from {matching['pair_count']:,} rows of `applications.csv` across {matching['job_count']} jobs. ROC-AUC is pooled across application pairs. Precision@5 and Precision@10 are macro averages of the per-job values; within a job, precision uses the top min(k, application count).",
        f"- The generator signal is reconstructed by replaying the seed-42 random draws and verified against all saved shortlist labels; its formula and threshold source is `{ceiling['source']}`.",
        f"- Eligibility correctness uses a seeded simple random sample of {eligibility['sample_size']:,} unique pairs from the full {eligibility['population_size']:,}-pair student/job Cartesian product. Ground truth is recomputed from CGPA, active backlogs, and eligible branches.",
        "- Readiness outcomes compare the readiness service score to whether a student has any accepted offer. Monotonicity compares the original score with a 0.1 CGPA increase where possible and with one additional active backlog.",
        f"- JD parsing uses {jds['labelled_description_count']} descriptions written and labelled before the first parser run. Missing parser CGPA value `0` accompanied by the parser's `Minimum CGPA not specified` warning is treated as not stated (`null`) for scoring.",
        f"- Pipeline match, eligibility and ranking metrics used `{results['metadata']['matching_mode_for_pipeline_metrics']}`. Readiness itself is rule-based and does not use embedding matching. The skill-pair benchmark compares exact-plus-alias matching with the configured embedding model at cosine threshold {skills['embedding_threshold']:.2f}.",
        "- The related-skill threshold sweep compares the ten hand-labelled related pairs with the ten different pairs; same/alias pairs are excluded because the matcher handles them in its exact/alias pass first.",
        "- Latency measurements ran directly against the service functions on the developer laptop recorded below; no HTTP or network request is included in timings.",
        "",
        "## Matching versus shortlisting",
        "",
        "| Method | ROC-AUC | Precision@5 (macro) | Precision@10 (macro) |",
        "|---|---:|---:|---:|",
    ]
    labels = {"matcher": "CampusLink matcher", "cgpa_only": "CGPA-only", "seeded_random": "Seeded random"}
    for method, values in matching["overall"].items():
        lines.append(
            f"| {labels[method]} | {_decimal(values['roc_auc'])} | {_percent(values['precision_at_5'])} | {_percent(values['precision_at_10'])} |"
        )
    matcher_auc = matching["overall"]["matcher"]["roc_auc"]
    cgpa_auc = matching["overall"]["cgpa_only"]["roc_auc"]
    bootstrap = matching["bootstrap_confidence_intervals"]
    if matcher_auc is not None and cgpa_auc is not None:
        comparison = "beats" if matcher_auc > cgpa_auc else "does not beat"
        lines += ["", f"The matcher {comparison} the CGPA-only baseline on pooled ROC-AUC ({_decimal(matcher_auc)} versus {_decimal(cgpa_auc)}). The report records this result as observed."]
    lines += [
        "",
        f"The deterministic pre-noise score has ROC-AUC {_decimal(ceiling['deterministic_base_signal_vs_observed_shortlisted_roc_auc'])} against the final shortlisted labels; the realized noisy generator score has ROC-AUC {_decimal(ceiling['upper_bound_under_generator_noise_roc_auc'])}, an oracle upper bound under the generator's Gaussian noise and 17% flip.",
        f"The deterministic signal's ROC-AUC of {_decimal(ceiling['deterministic_base_signal_vs_observed_shortlisted_roc_auc'])} is the realistic ceiling for any scorer because its Gaussian noise and 17% label flips are random and unobservable; the 0.784 oracle uses the hidden draw and is not a reachable target.",
        f"The matcher retains {_percent(ceiling['matcher_auc_chance_adjusted_share_of_deterministic_signal'])} of the deterministic signal's above-chance AUC ((matcher AUC - 0.5) / (deterministic AUC - 0.5)). The oracle share ({_percent(ceiling['matcher_auc_share_of_oracle_signal_diagnostic_only_pct'] / 100 if ceiling['matcher_auc_share_of_oracle_signal_diagnostic_only_pct'] is not None else None)}) is reported only as a diagnostic; the noisy signal against pre-flip labels has ROC-AUC {_decimal(ceiling['noisy_signal_vs_preflip_label_roc_auc_no_17_percent_flip'])}.",
        "",
        f"Seeded bootstrap: {bootstrap['requested_resamples']:,} application-row resamples with seed {bootstrap['seed']}, percentile 95% confidence intervals.",
        "| Metric | 95% confidence interval |",
        "|---|---:|",
        *[
            f"| {label} ROC-AUC | [{_decimal(bootstrap['roc_auc'][key]['lower_95'])}, {_decimal(bootstrap['roc_auc'][key]['upper_95'])}] |"
            for key, label in (("matcher", "Matcher"), ("cgpa_only", "CGPA-only"), ("seeded_random", "Seeded random"))
        ],
        f"| Paired difference, matcher minus CGPA-only AUC | [{_decimal(bootstrap['paired_difference_matcher_minus_cgpa_only']['lower_95'])}, {_decimal(bootstrap['paired_difference_matcher_minus_cgpa_only']['upper_95'])}] |",
        "The matcher is not distinguishable from CGPA-only by this bootstrap interval." if bootstrap["difference_interval_contains_zero"] else "The paired bootstrap interval for matcher minus CGPA-only excludes zero.",
    ]
    lines += [
        "",
        "### Per-job results",
        "",
        "| Job | Pairs | Matcher AUC | Matcher P@5 | Matcher P@10 | CGPA AUC | CGPA P@5 | CGPA P@10 | Random AUC | Random P@5 | Random P@10 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for job_id, values in sorted(matching["per_job"].items()):
        matcher_values = values["matcher"]
        cgpa_values = values["cgpa_only"]
        random_values = values["seeded_random"]
        lines.append(
            f"| {job_id} | {values['application_count']} | {_decimal(matcher_values['roc_auc'])} | {_percent(matcher_values['precision_at_5'])} | {_percent(matcher_values['precision_at_10'])} | {_decimal(cgpa_values['roc_auc'])} | {_percent(cgpa_values['precision_at_5'])} | {_percent(cgpa_values['precision_at_10'])} | {_decimal(random_values['roc_auc'])} | {_percent(random_values['precision_at_5'])} | {_percent(random_values['precision_at_10'])} |"
        )
    job_diag = matching["per_job_diagnostic"]
    lines.append(
        f"Per-job samples are small ({job_diag['minimum_application_count']} to {job_diag['maximum_application_count']} pairs), so per-job AUCs are noisy; the matcher is below 0.5 on {job_diag['matcher_auc_below_0_5_job_count']} of {job_diag['job_count']} jobs."
    )

    monotonic = readiness["monotonicity"]
    lines += [
        "",
        "## Eligibility, readiness, and outcomes",
        "",
        f"Eligibility agreed with direct gate recomputation for {eligibility['agreement_count']:,}/{eligibility['sample_size']:,} sampled pairs ({_percent(eligibility['agreement_rate'])}). Disagreements: {len(eligibility['disagreements'])}.",
        "",
        "| Readiness/outcome measure | Result |",
        "|---|---:|",
        f"| Students placed / unplaced | {readiness['placed_count']} / {readiness['unplaced_count']} |",
        f"| Readiness ROC-AUC for placed label | {_decimal(readiness['readiness_roc_auc_for_placed'])} |",
        f"| Mean readiness, placed | {_decimal(readiness['mean_readiness_placed'])} |",
        f"| Mean readiness, unplaced | {_decimal(readiness['mean_readiness_unplaced'])} |",
        f"| CGPA raise never lowers score | {monotonic['cgpa_never_lowers_score']} ({monotonic['cgpa_raise_checks']} checks) |",
        f"| Backlog increase never raises score | {monotonic['backlog_never_raises_score']} ({monotonic['backlog_increase_checks']} checks) |",
        "",
        "## JD parser accuracy",
        "",
        "| Field | Correct | Total | Accuracy |",
        "|---|---:|---:|---:|",
    ]
    for field, values in jds["field_accuracy"].items():
        lines.append(f"| {field} | {values['correct']} | {values['total']} | {_percent(values['accuracy'])} |")
    skill_metrics = jds["skill_level_precision_recall_f1"]
    lines += [
        f"| **All field values** | {round(jds['overall_field_accuracy'] * jds['labelled_description_count'] * 6)} | {jds['labelled_description_count'] * 6} | **{_percent(jds['overall_field_accuracy'])}** |",
        "",
        f"Skill extraction over canonical skill occurrences: precision {_decimal(skill_metrics['precision'])}, recall {_decimal(skill_metrics['recall'])}, F1 {_decimal(skill_metrics['f1'])} ({skill_metrics['true_positive']}/{skill_metrics['expected_count']} labelled skills found; {skill_metrics['predicted_count']} predicted).",
        "",
        "Parser misses are retained as misses. No labels were changed after the first parser run: JD07's expected role is its first line under the specified fallback; JD13's `at least 7.1` and JD20's `70 percent` state numeric minimums in the text; and JD18 explicitly names Structural Analysis, Revit, and STAAD.Pro, of which those three names are absent from the current parser catalog. These are parser or catalog coverage misses, not label corrections.",
    ]
    if jds["incorrect_cases"]:
        lines += ["", "| JD | Incorrect fields | Expected | Parsed |", "|---|---|---|---|"]
        for case in jds["incorrect_cases"]:
            wrong = [field for field, correct in case["field_correct"].items() if not correct]
            expected = {field: case["expected"][field] for field in wrong}
            actual = {field: case["actual"][field] for field in wrong}
            lines.append(f"| {case['id']} | {', '.join(wrong)} | `{_safe_cell(json.dumps(expected, ensure_ascii=False))}` | `{_safe_cell(json.dumps(actual, ensure_ascii=False))}` |")

    exact = skills["exact_plus_alias"]
    lines += [
        "",
        "## Skill matching",
        "",
        f"The hand-labelled set has {skills['pair_count']} pairs: {skills['class_counts']['same_or_alias']} same/alias, {skills['class_counts']['related']} related, and {skills['class_counts']['different']} different.",
        "",
        "| Matcher | Accuracy | Precision | Recall | F1 |",
        "|---|---:|---:|---:|---:|",
        f"| Exact plus alias | {_percent(exact['accuracy'])} | {_decimal(exact['precision'])} | {_decimal(exact['recall'])} | {_decimal(exact['f1'])} |",
    ]
    if skills["embedding_loaded"]:
        embedding = skills["embedding_plus_alias"]
        lines.append(f"| Embedding plus alias, threshold {skills['embedding_threshold']:.2f} | {_percent(embedding['accuracy'])} | {_decimal(embedding['precision'])} | {_decimal(embedding['recall'])} | {_decimal(embedding['f1'])} |")
        lines.append("")
        lines.append("The encoder loaded successfully, and embedding-plus-alias matching did not improve accuracy over exact-plus-alias on this set (both are 66.67%).")
        related = [item for item in skills["pair_results"] if item["category"] == "related"]
        related_matched = sum(bool(item["embedding_match"]) for item in related)
        lines.append(f"At the configured 0.75 threshold {related_matched} of the ten related pairs matched, so the embedding model does not change matching results on this set; the threshold is conservative and was not tuned.")
        lines.append("The 30 pairs written by the team are too few to tune a semantic similarity threshold on.")
        lines += [
            "",
            "| Related-vs-different threshold | Precision | Recall | TP | FP | FN |",
            "|---:|---:|---:|---:|---:|---:|",
        ]
        for item in skills["related_threshold_sweep"]:
            lines.append(f"| {item['threshold']:.2f} | {_decimal(item['precision'])} | {_decimal(item['recall'])} | {item['true_positive']} | {item['false_positive']} | {item['false_negative']} |")
        lines += ["", "Cosine similarity for every labelled related pair:", "", "| Candidate | Required | Cosine similarity |", "|---|---|---:|"]
        for item in skills["related_pair_similarities"]:
            lines.append(f"| {item['candidate']} | {item['required']} | {_decimal(item['cosine_similarity'], 6)} |")
    else:
        lines.append("")
        lines.append(f"Embedding scores were skipped because the model did not load: {skills['embedding_skip_reason']}")
        lines.append("The 30 pairs written by the team are too few to tune a semantic similarity threshold on.")

    lines += [
        "",
        "## Risk model",
        "",
        f"Selected model: `{risk['selected_model']}`. The saved stratified test metrics (n={risk['test_size']}) are:",
        "",
        "| Accuracy | Precision | Recall | F1 | ROC-AUC | Always-unplaced accuracy baseline |",
        "|---:|---:|---:|---:|---:|---:|",
        f"| {_decimal(risk['accuracy'])} | {_decimal(risk['precision'])} | {_decimal(risk['recall'])} | {_decimal(risk['f1'])} | {_decimal(risk['roc_auc'])} | {_decimal(risk['always_unplaced_accuracy_baseline'])} |",
        "",
        f"Confusion matrix, actual rows [placed, unplaced] and predicted columns [placed, unplaced]: `{json.dumps(risk['confusion_matrix'])}`.",
        "",
        "About 73 percent of this synthetic cohort is unplaced, so accuracy near 0.77 is close to the always-unplaced baseline of 0.73. Features such as interviews attended come from the same placement funnel that produces the label, which creates additional leakage risk.",
        "",
        "## Latency and scale",
        "",
        f"Machine: {latency['machine_description']}",
        "",
        "| Operation | Median latency | Measurement |",
        "|---|---:|---|",
        f"| One match pair | {_decimal(latency['match_one_pair']['median_ms'], 4)} ms | 50 calls after warm-up ({latency['match_one_pair']['pair']['student_id']} x {latency['match_one_pair']['pair']['job_id']}) |",
        f"| Rank 100 students | {_decimal(latency['rank_100_students']['median_ms'], 4)} ms | 3 runs after warm-up; {latency['rank_100_students']['actual_count']} students |",
        f"| Rank 500 students | {_decimal(latency['rank_500_students']['median_ms'], 4)} ms | 3 runs after warm-up; {latency['rank_500_students']['actual_count']} students |",
        "",
        "## Limitations",
        "",
        "- The data is synthetic.",
        "- There is partial circularity between the data generator and the matcher: shortlist outcomes depend partly on required-skill overlap and CGPA, signals that the matcher also uses. About 17 percent of shortlist outcomes were flipped.",
        "- The JD and skill-pair hand-labelled sets are small and were written by the team.",
        "- There are no real placement outcomes in this evaluation, so these figures are not real-world accuracy.",
        "- The figures show that the pipeline works and is internally consistent; they do not establish real-world accuracy.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    results = json.loads(RESULTS_PATH.read_text(encoding="utf-8"))
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(render(results), encoding="utf-8")
    print(f"Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
